-- ----------------------------------------------------------------------------
-- ตัวอย่าง 1: สร้างคำขอเช่า (RentalOrder)
-- ปัญหาที่ต้องกัน: 2 คนกดจองสินค้าชิ้นเดียวกัน วันเดียวกัน พร้อมกันเป๊ะ (race condition)
--
-- วิธีแก้ 2 ชั้น:
--   ชั้นที่ 1 (แน่นอนที่สุด): EXCLUDE constraint "no_overlapping_active_bookings"
--            ที่ใส่ไว้ใน RentalOrder ตอน CREATE TABLE แล้ว — ต่อให้ทั้งสอง
--            transaction วิ่งพร้อมกันเป๊ะ ฐานข้อมูลจะ error ให้กับ transaction
--            ที่ insert เข้ามาทีหลังโดยอัตโนมัติ ไม่ต้องเขียนโค้ดเช็คเอง
--   ชั้นที่ 2: ห่อด้วย BEGIN/COMMIT เพื่อให้ backend จับ error แล้วแจ้ง user
--            ว่า "สินค้านี้เพิ่งถูกจองไปเมื่อครู่ กรุณาเลือกวันอื่น" ได้ทันที
--            แทนที่จะปล่อยให้ error หลุดไปเป็น 500 เฉยๆ
-- ----------------------------------------------------------------------------

BEGIN;

INSERT INTO RentalOrder (user_id, item_id, start_date, end_date, rental_fee, deposit, status)
VALUES (
  '11111111-1111-1111-1111-111111111111',  -- user_id ของผู้เช่า
  '22222222-2222-2222-2222-222222222222',  -- item_id
  '2026-08-15',
  '2026-08-17',
  900.00,
  1500.00,
  'requested'
);
-- ถ้ามี order อื่นที่ status ยัง active อยู่ ทับช่วงวันที่นี้ของ item เดียวกัน
-- บรรทัดนี้จะ error ทันทีด้วย: "conflicting key value violates exclusion constraint"

COMMIT;
-- ฝั่ง backend: ถ้า COMMIT/INSERT throw error ที่มีคำว่า
-- "no_overlapping_active_bookings" ให้ตีความว่าเป็นเคสจองซ้อน แล้วตอบ user ตามนั้น


-- ----------------------------------------------------------------------------
-- ตัวอย่าง 2: เจ้าของอนุมัติคำขอเช่า + ระบบต้องล็อกไม่ให้แถวนี้ถูกแก้พร้อมกัน 2 ที่
-- เช่น เจ้าของกด "อนุมัติ" พร้อมกับที่ผู้เช่ากด "ยกเลิก" ในเวลาไล่เลี่ยกัน
-- ใช้ SELECT ... FOR UPDATE เพื่อ "ล็อกแถว" ไว้ก่อนแก้ ป้องกัน transaction อื่น
-- มาอ่าน/แก้แถวเดียวกันพร้อมกัน (แถวที่สองจะต้องรอจนแถวแรก COMMIT/ROLLBACK เสร็จ)
-- ----------------------------------------------------------------------------

BEGIN;

-- ล็อกแถวนี้ไว้ก่อน ห้าม transaction อื่นมาแก้พร้อมกัน
SELECT status FROM RentalOrder
WHERE order_id = '33333333-3333-3333-3333-333333333333'
FOR UPDATE;

-- เช็ค status ในโค้ด backend ก่อนว่ายังเป็น 'requested' อยู่จริงไหม
-- (ป้องกันเคสที่มันถูกเปลี่ยนไปแล้วโดย transaction ที่เพิ่ง COMMIT ไปก่อนหน้า)
-- ถ้าใช่ ค่อย UPDATE ต่อ:

UPDATE RentalOrder
SET status = 'awaiting_payment', updated_at = NOW()
WHERE order_id = '33333333-3333-3333-3333-333333333333';

COMMIT;


-- ----------------------------------------------------------------------------
-- ตัวอย่าง 3: ผู้เช่าชำระเงิน — ต้องอัปเดตหลายตารางพร้อมกันแบบ "ทั้งหมดหรือไม่ทำเลย"
-- (all-or-nothing) เพราะถ้า insert Payment สำเร็จ แต่ update RentalOrder ล้มเหลว
-- ระบบจะเข้าใจผิดว่ายังไม่จ่ายเงิน ทั้งที่มีการโอนเงินไปแล้วจริง
-- การห่อด้วย transaction เดียวกันคือหัวใจของการแก้ปัญหานี้
-- ----------------------------------------------------------------------------

BEGIN;

INSERT INTO Payment (order_id, user_id, slip_image_url, status)
VALUES (
  '33333333-3333-3333-3333-333333333333',
  '11111111-1111-1111-1111-111111111111',
  'https://storage.example.com/slips/xxxx.jpg',
  'paid'
);

UPDATE RentalOrder
SET status = 'paid',
    total_paid = rental_fee + deposit,
    fee = rental_fee * 0.20,
    net_income = rental_fee - (rental_fee * 0.20),
    updated_at = NOW()
WHERE order_id = '33333333-3333-3333-3333-333333333333';

-- ถ้าทั้งสองคำสั่งสำเร็จ ค่อย COMMIT
-- ถ้าคำสั่งไหนพลาด (เช่น network หลุดกลางทาง) ให้ ROLLBACK เพื่อยกเลิกทั้งหมด
-- (ไม่มีการ "จ่ายเงินสำเร็จแต่ order ไม่อัปเดต" หลงเหลืออยู่แน่นอน)
COMMIT;


