-- จะเป็นคนละ transaction กัน ไม่ auto-wrap ให้ ถ้าต้องการ atomic แบบตัวอย่าง 2-3
-- ด้านบน ต้องเขียนเป็น Postgres Function (RPC) แล้วเรียกผ่าน supabase.rpc(...)
-- เพราะโค้ดข้างในฟังก์ชันจะรันอยู่ใน transaction เดียวกันโดยอัตโนมัติ
